#!/usr/bin/env python3
"""results/reference_results.json + reference_zoo.csv -> slides/figures/numbers.tex (LaTeX macros).

The slides and the exam use these macros, so a new reference run updates every number automatically.
"""
import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
R = json.loads((HERE / "results/reference_results.json").read_text())
zoo = pd.read_csv(HERE / "results/reference_zoo.csv")


def pct(x, d=1):
    return f"{100 * x:.{d}f}\\,\\%"


m = {}
ds = R["dataset"]
m["RefCrops"] = f"{ds['crops_clean']:,}".replace(",", "{,}")
m["RefDives"] = f"{ds['dives']:,}".replace(",", "{,}")
m["RefTopTenDives"] = pct(ds["top10_dives_share"], 0)
t = R["two_features"]
m.update(RefTwoTrain=t["n_train"], RefTwoTest=t["n_test"], RefThr=t["threshold"],
         RefThrTrain=pct(t["thr_train_acc"]), RefThrTest=pct(t["thr_test_acc"]))
cs = pd.DataFrame(R["lab1_colourstats"]).set_index(["target", "classifier"])["test"]
for tgt, T in [("phylum", "Phylum"), ("label", "Label")]:
    for c, C in [("majority", "Majority"), ("nearest_centroid", "Centroid"), ("knn", "Knn"), ("decision_tree", "Tree")]:
        m[f"RefCS{T}{C}"] = pct(cs[(tgt, c)])
m["RefCSLabelBest"] = pct(cs["label"].drop("majority").max())

pretty = {"majority": "majority baseline", "nearest_centroid": "nearest centroid", "knn": "5-nearest neighbours",
          "decision_tree": "decision tree", "random_forest": "random forest",
          "logistic_regression": "logistic regression", "mlp": "neural network (MLP)"}
cnn = zoo[zoo.features == "cnn"].set_index("classifier")
best = cnn["accuracy"].idxmax()
m["RefZooBestName"] = pretty[best]
m["RefZooBest"] = pct(cnn["accuracy"].max())
m["RefZooBestPixels"] = pct(zoo[zoo.features == "pixels"]["accuracy"].max())
m["RefZooBestColour"] = pct(zoo[zoo.features == "colour_stats"]["accuracy"].max())
rows = []
for c, r in cnn.iterrows():
    secs = r["fit_seconds"]
    rows.append(f"{pretty[c]} & {pct(r['train_accuracy'])} & {pct(r['accuracy'])} & "
                f"{'$<$1' if secs < 1 else f'{secs:.0f}'}\\,s \\\\")
m["RefZooRows"] = "\n".join(rows)

sp = pd.DataFrame(R["splits"]).set_index(["split", "classifier"])
for s, S in [("random", "Random"), ("image", "Image"), ("dive", "Dive")]:
    m[f"Ref{S}Acc"] = pct(sp.loc[(s, "logistic_regression"), "accuracy"])
    m[f"Ref{S}AccKnn"] = pct(sp.loc[(s, "knn"), "accuracy"])
    m[f"RefTrainLogreg{S}"] = pct(sp.loc[(s, "logistic_regression"), "train_accuracy"])
    m[f"RefTrainKnn{S}"] = pct(sp.loc[(s, "knn"), "train_accuracy"])
m["RefSeenDiveRandom"] = pct(sp.loc[("random", "logistic_regression"), "share_dive_seen"], 0)

order = ["species", "genus", "family", "order", "class", "phylum", "subfamily", "gigaclass", "infraorder", "subphylum"]
rr = {r["label_rank"]: r for r in R["recall_by_label_rank"]}
other = [rr[k] for k in rr if k not in order[:6]]
rows = [f"{k} & {int(rr[k]['size'])} & {pct(rr[k]['mean'], 0)} \\\\" for k in order[:6] if k in rr]
if other:
    n = sum(o["size"] for o in other)
    mean = sum(o["mean"] * o["size"] for o in other) / n
    rows.append(f"other rank & {int(n)} & {pct(mean, 0)} \\\\")
m["RefRecallRows"] = "\n".join(rows)

sev = R["severity_dive"]
m["RefSevKingdom"] = pct(sev.get("kingdom", 0) + sev.get("none", 0), 0)
m["RefSevNear"] = pct(sev.get("order", 0) + sev.get("family", 0) + sev.get("genus", 0), 0)
m["RefRandPhylumAcc"] = pct(R["accuracy_at_rank"]["random"]["phylum"])
m["RefDivePhylumAcc"] = pct(R["accuracy_at_rank"]["dive"]["phylum"])
m["RefDiveFone"] = f"{R['dive_logreg']['macro_f1']:.3f}"
m["RefDiveAccSingle"] = pct(R["dive_logreg"]["accuracy"])

out = ["% generated by write_numbers.py from results/reference_results.json - do not edit"]
out += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
(HERE / "slides/figures/numbers.tex").write_text("\n".join(out) + "\n")
print("\n".join(out))
